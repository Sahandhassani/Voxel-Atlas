import assert from 'node:assert/strict';
import { newBoard, rollBoard, boardAction, canBuild, newMarket, marketTrade, advanceMarket, portfolioValue } from '../public/game-engine.mjs';

let board = newBoard();
assert.equal(boardAction(board, 'build'), board, 'A station cannot be built before rolling');
board = rollBoard(board, 1);
assert.equal(board.supplies.timber, 5);
assert.equal(rollBoard(board, 2), board, 'Only one roll per turn');
assert.equal(canBuild(board), true);
board = boardAction(board, 'build');
assert.equal(board.stations.length, 1);
assert.deepEqual(board.supplies, {timber: 3, energy: 0, knowledge: 0});
assert.equal(board.turn, 2);
const poor = rollBoard({...newBoard(), supplies: {timber: 0, energy: 0, knowledge: 0}}, 1);
assert.equal(boardAction(poor, 'build'), poor, 'Cannot overspend materials');
let lost = newBoard();
for (let i = 0; i < 16; i++) lost = boardAction(rollBoard(lost, 1), 'gather', 'timber');
assert.equal(lost.result, 'lost');
assert.equal(rollBoard(lost, 4), lost, 'Finished runs cannot continue');
let win = {...newBoard(), supplies: {timber: 20, energy: 20, knowledge: 20}};
for (let i = 0; i < 4; i++) win = boardAction(rollBoard(win, 1), 'build');
assert.equal(win.result, 'won');
assert.equal(win.turn, 4);
assert.equal(newBoard().stations.length, 0, 'Reset is clean');

let market = newMarket(() => .5);
assert.equal(marketTrade(market, 'sell'), market, 'Cannot sell nonexistent holdings');
assert.equal(marketTrade(market, 'buy', 11), market, 'Cannot spend more than available cash');
market = marketTrade(market, 'buy', 10);
assert.equal(market.cash, 0); assert.equal(market.shares, 10);
assert.equal(portfolioValue(market), 1000);
assert.equal(marketTrade(market, 'buy'), market);
market = marketTrade(market, 'sell', 2);
assert.equal(market.cash, 200); assert.equal(market.shares, 8);
for (let i = 0; i < 24; i++) market = advanceMarket(market);
assert.equal(market.finished, true); assert.equal(market.day, 23);
assert.equal(marketTrade(market, 'buy'), market);
assert.equal(newMarket().cash, 1000);
console.log('Game checks passed: action phases, costs, wins/losses, clean resets, trade limits, session end.');
